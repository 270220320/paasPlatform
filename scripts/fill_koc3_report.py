def main():
    shutil.copyfile(PATH, BACKUP)
    print(f"备份完成 -> {BACKUP}")

    doc = Document(PATH)

    sug_tbl, req_tbl = None, None
    for t in doc.tables:
        hdr = ' | '.join(c.text.strip() for c in t.rows[0].cells)
        if '是否解决' in hdr:
            sug_tbl = t
        elif '需求标题' in hdr:
            req_tbl = t
    assert sug_tbl is not None, "未找到改进建议表"
    assert req_tbl is not None, "未找到新增需求表"

    fill_table(sug_tbl, SUGGESTIONS)
    fill_table(req_tbl, REQUIREMENTS)

    doc.save(PATH)
    print(f"已写入并保存 -> {PATH}")
    print(f"改进建议 {len(SUGGESTIONS)} 条，新增需求 {len(REQUIREMENTS)} 条")

