# ---------------- 工具函数 ----------------

def set_cell_text(cell, text):
    """覆盖单元格文本：保留首段落首run格式，清除多余段落/run"""
    # 删除第一个段落之外的段落
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    p = cell.paragraphs[0]
    runs = p.runs
    if not runs:
        run = p.add_run(text)
    else:
        runs[0].text = text
        for r in runs[1:]:
            r._element.getparent().remove(r._element)

def fill_table(table, data):
    """用 data 填充表格：覆盖现有数据行，不足的行以第一数据行为模板追加"""
    tmpl = copy.deepcopy(table.rows[1]._tr)  # 格式模板（首数据行）
    n_existing = len(table.rows) - 1
    total = len(data)
    # 追加缺失的行
    for _ in range(total - n_existing):
        table._tbl.append(copy.deepcopy(tmpl))
    # 填写全部数据行
    for i, row_data in enumerate(data):
        row = table.rows[i + 1]
        for cell, text in zip(row.cells, row_data):
            set_cell_text(cell, text)

